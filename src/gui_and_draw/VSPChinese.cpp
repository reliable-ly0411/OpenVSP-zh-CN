std::string VSPTranslateMenuPath( const std::string &path )
{
    static const std::unordered_map<std::string, std::string> view_labels = {
        { "Top", "顶视图" }, { "Bottom", "底视图" },
        { "Left", "左视图" }, { "Right", "右视图" },
        { "Front", "前视图" }, { "Rear", "后视图" }, { "Center", "居中" }
    };
    const bool view_menu = path.compare( 0, 5, "View/" ) == 0;
    std::string result;
    std::size_t start = 0;
    while ( start <= path.size() )
    {
        const std::size_t slash = path.find( '/', start );
        const std::size_t count = slash == std::string::npos ? std::string::npos : slash - start;
        if ( !result.empty() )
        {
            result += '/';
        }
        const std::string label = path.substr( start, count );
        const auto view = view_labels.find( label );
        result += view_menu && start > 0 && view != view_labels.end() ?
                  view->second : VSPTranslate( label );
        if ( slash == std::string::npos )
        {
            break;
        }
        start = slash + 1;
    }
    return result;
}

